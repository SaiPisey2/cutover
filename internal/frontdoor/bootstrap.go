package frontdoor

import (
	"bytes"
	"fmt"
	"net"
	"strconv"
	"strings"
	"text/template"
)

// BootstrapConfig is where Envoy finds cutover's xDS server ("unix:/path"
// or a loopback IP:port) and where it serves its own admin (loopback).
type BootstrapConfig struct {
	XDS   string
	Admin string
}

// latencyBuckets are finer than Envoy's defaults (0.5, 1, 5, 10, 25, 50,
// 100, 250, ...): the p99 tripwire compares bucket bounds, and a factor
// of 2 needs neighbouring bounds closer than 2x apart.
const latencyBuckets = "[1, 2, 5, 10, 15, 20, 30, 40, 50, 75, 100, 150, 200, 300, 400, 500, 750, 1000, 1500, 2000, 3000, 5000, 10000, 30000, 60000]"

// stats_flush_interval is 1s, not Envoy's 5s default: histograms (and so
// p99) only change in /stats/prometheus at a flush, and a window shorter
// than the interval would see no latency at all.
var bootstrapTmpl = template.Must(template.New("b").Parse(`# Envoy bootstrap for cutover's front door. Generated by cutover envoy-bootstrap.
node:
  id: {{.Node}}
  cluster: cutover
admin:
  address:
    socket_address:
          address: {{.AdminIP}}
          port_value: {{.AdminPort}}
dynamic_resources:
  ads_config:
    api_type: GRPC
    transport_api_version: V3
    grpc_services:
    - envoy_grpc:
        cluster_name: cutover_xds
  cds_config:
    resource_api_version: V3
    ads: {}
  lds_config:
    resource_api_version: V3
    ads: {}
static_resources:
  clusters:
  - name: cutover_xds
    type: STATIC
    connect_timeout: 1s
    typed_extension_protocol_options:
      envoy.extensions.upstreams.http.v3.HttpProtocolOptions:
        "@type": type.googleapis.com/envoy.extensions.upstreams.http.v3.HttpProtocolOptions
        explicit_http_config:
          http2_protocol_options: {}
    load_assignment:
      cluster_name: cutover_xds
      endpoints:
      - lb_endpoints:
        - endpoint:
            address:
{{- if .Pipe}}
              pipe:
                path: {{.Pipe}}
{{- else}}
              socket_address:
                address: {{.XDSIP}}
                port_value: {{.XDSPort}}
{{- end}}
stats_flush_interval: 1s
stats_config:
  histogram_bucket_settings:
  - match:
      suffix: upstream_rq_time
    buckets: ` + latencyBuckets + `
`))

func loopbackIPPort(addr string) (string, int, error) {
	h, p, err := net.SplitHostPort(addr)
	if err != nil {
		return "", 0, fmt.Errorf("%q is not IP:port", addr)
	}
	ip := net.ParseIP(h)
	if ip == nil || !ip.IsLoopback() {
		return "", 0, fmt.Errorf("%q: want a loopback IP address (127.0.0.1 or ::1)", addr)
	}
	n, err := strconv.Atoi(p)
	if err != nil || n < 1 || n > 65535 {
		return "", 0, fmt.Errorf("%q: bad port", addr)
	}
	return h, n, nil
}

func Bootstrap(c BootstrapConfig) (string, error) {
	d := map[string]any{"Node": NodeID}
	ip, port, err := loopbackIPPort(c.Admin)
	if err != nil {
		return "", fmt.Errorf("admin: %w", err)
	}
	d["AdminIP"], d["AdminPort"] = ip, port
	if path, ok := strings.CutPrefix(c.XDS, "unix:"); ok {
		if !strings.HasPrefix(path, "/") {
			return "", fmt.Errorf("xds: unix socket path must be absolute")
		}
		d["Pipe"] = path
	} else {
		ip, port, err := loopbackIPPort(c.XDS)
		if err != nil {
			return "", fmt.Errorf("xds: %w", err)
		}
		d["XDSIP"], d["XDSPort"] = ip, port
	}
	var b bytes.Buffer
	if err := bootstrapTmpl.Execute(&b, d); err != nil {
		return "", err
	}
	return b.String(), nil
}
